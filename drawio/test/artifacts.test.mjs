test("NC-39 every shipped pill geometry equals the shared contract for the state it presents", () => {
  const violations = [];
  for (const name of examples) {
    const cells = canonicalModel(shipped[name]).cells;
    for (const entity of objectAttributes(shipped[name], "entity")) {
      const label = entity.ahmComputedState === "Unknown" && entity.ahmAuthoredState === "standby"
        ? "Standby" : entity.ahmComputedState;
      const sized = PILL.width[label];
      const pill = cells.get(`${entity.cell.id}-state`);
      const text = cells.get(`${entity.cell.id}-state-label`);
      const record = (actual, expected, what) => {
        if (String(actual) !== String(expected)) {
          violations.push(`${name}/${entity.cell.id} ${what} ${actual} != ${expected} (${label})`);
        }
      };
      if (!sized) { violations.push(`${name}/${entity.cell.id} presents "${label}"`); continue; }
      record(pill.geometry.w, sized.pill, "pill width");
      // The right edge is the card's own inset, so x is fully determined by the contract.
      record(pill.geometry.x, 212 - sized.pill, "pill x");
      record(text.geometry.w, sized.label, "label width");
      record(text.geometry.x, PILL.textX, "label x");
    }
  }
  assert.deepEqual(violations, []);
});

