test("NC-31 negative control (a): the real interactively-saved artifact is reported as drifted", () => {
  // The exact bytes Draw.io/VS Code wrote over `examples/kitchen-sink.drawio.svg` at 2026-07-26
  // 23:18:20, preserved before anything regenerated them. This is the failure the guard exists for.
  const real = readDrawioSvg(resolve(root, "test/fixtures/interactively-saved-kitchen-sink.drawio.svg"));
  const drift = driftReport(built["kitchen-sink"], real.model);
  const cells = new Set(drift.map((line) => line.split(":")[0]));
  console.log(`NC-31 real drift fixture: driftedCells=${cells.size} lines=${drift.length}`);
  console.log(drift.filter((line) => line.startsWith("shop")).join("\n"));
  assert.ok(drift.length > 0, "the real interactive save must be reported as drifted");
  // Named cells, not "something changed": the pill the runtime resized wrongly, the recoloured
  // card, the pre-quantisation lane heights and the dropped ahmLabel attributes.
  assert.ok(cells.has("shop"), "the moved entity must be named");
  assert.ok(cells.has("shop-state-label"), "the stale pill label must be named");
  assert.ok(cells.has("lane-1"), "the pre-quantisation lane height must be named");
  // The save baked in exactly the C-12 runtime defect: a `Degraded` label left inside a
  // Healthy-sized 73px pill with a 37px label cell, which the shared contract now sizes at 83/47.
  assert.ok(drift.some((line) => /^shop-state: w built="83" artifact="73"/.test(line)),
    "the under-sized runtime pill must be reported");
  assert.ok(drift.some((line) => /^shop-state-label: w built="47" artifact="37"/.test(line)),
    "the under-sized runtime pill label must be reported");
  assert.ok(drift.some((line) => /^web-signal-0-label: sem .*ahmLabel=Web latency/.test(line)),
    "the dropped ahmLabel attributes must be reported");
});

test("NC-31 negative control (b): each single-field mutation is caught individually", () => {
  // Applied in memory to a *good* artifact — one semantic attribute, one geometry number, one style
  // value — so each rule of the contract is shown to discriminate on its own.
  const mutations = [
    {
      name: "ahm state attribute",
      apply: (xml) => xml.replace(
        /(<object [^>]*ahmId="web"[^>]*)ahmComputedState="Healthy"/,
        '$1ahmComputedState="Degraded"',
      ),
      expect: /^web: sem .*ahmComputedState=Healthy.*ahmComputedState=Degraded/,
    },
    {
      name: "geometry number",
      apply: (xml) => xml.replace(
        /(<mxCell[^>]*parent="web-state"[^>]*>\s*<mxGeometry x=")7(")/,
        "$19$2",
      ),
      expect: /^web-state-dot: x built="7" artifact="9"/,
    },
    {
      name: "style value",
      apply: (xml) => xml.replace(
        /(<object[^>]*id="web-state-dot"[^>]*>\s*<mxCell[^>]*style="[^"]*)fillColor=#4c9a2a;/,
        "$1fillColor=#c50f18;",
      ),
      expect: /^web-state-dot: style .*fillColor=#4c9a2a.*fillColor=#c50f18/,
    },
  ];
  for (const mutation of mutations) {
    const mutated = mutation.apply(shipped.hero);
    assert.notEqual(mutated, shipped.hero, `${mutation.name} did not apply`);
    const drift = driftReport(built.hero, mutated);
    assert.ok(drift.some((line) => mutation.expect.test(line)),
      `${mutation.name} was not reported: ${JSON.stringify(drift.slice(0, 5))}`);
    console.log(`NC-31 mutation "${mutation.name}" -> ${drift.find((line) => mutation.expect.test(line))}`);
  }
});

test("NC-31 negative control (c): harmless Draw.io save differences stay silent", () => {
  // Everything Draw.io was measured to change on an *innocent* save: style key order, the omitted
  // connectable default, omitted zero-valued geometry attributes and the editor's own view state.
  const harmless = shipped.hero
    .replace(
      /style="ellipse;html=0;shadow=0;fontFamily=Helvetica;noLabel=1;fillColor=#4c9a2a;strokeColor=none;"/g,
      'style="strokeColor=none;fillColor=#4c9a2a;noLabel=1;fontFamily=Helvetica;shadow=0;html=0;ellipse;"',
    )
    .replace(/ connectable="1"/g, "")
    .replace(/<mxGeometry x="7" y="5" width="10" height="10" as="geometry"/g,
      '<mxGeometry x="7" y="5" width="10" height="10" as="geometry"')
    .replace(/<mxGeometry x="26" y="0" width="(\d+)" height="20" as="geometry"/g,
      '<mxGeometry x="26" width="$1" height="20" as="geometry"')
    .replace(/<mxGraphModel dx="\d+" dy="\d+"/, '<mxGraphModel dx="911" dy="507" pageScale="2"');
  assert.notEqual(harmless, shipped.hero, "the harmless mutations did not apply");
  assert.match(harmless, /style="strokeColor=none;fillColor=#4c9a2a;/, "style re-order applied");
  assert.doesNotMatch(harmless, / connectable="1"/, "connectable default dropped");
  assert.match(harmless, /<mxGeometry x="26" width="\d+" height="20"/, "zero geometry attribute dropped");
  assert.deepEqual(driftReport(built.hero, harmless), [],
    "the normalisation contract reported a harmless Draw.io serialisation difference");
});

