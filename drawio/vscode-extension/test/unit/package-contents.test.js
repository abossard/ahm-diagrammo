// Package contents audit (V-10, C-23.2): the built VSIX must contain exactly the pinned
// entry set, with every shipped asset matching the source-of-truth digest.
"use strict";
const { describe, it } = require("node:test");
const assert = require("node:assert/strict");
const { spawnSync } = require("child_process");
const path = require("path");
const fs = require("fs");
const crypto = require("crypto");

const extRoot = path.join(__dirname, "..", "..");
const vsixFiles = fs.readdirSync(extRoot).filter(f => f.endsWith(".vsix")).sort();

// Exact zip payload, sorted. Adding or removing any entry fails this audit.
const EXPECTED_ENTRIES = [
  "[Content_Types].xml",
  "extension.vsixmanifest",
  "extension/LICENSE.txt",
  "extension/assets/library/ahm-diagrammo.xml",
  "extension/assets/manifest.json",
  "extension/assets/plugin/ahm-diagrammo.plugin.js",
  "extension/changelog.md",
  "extension/icon.png",
  "extension/package.json",
  "extension/readme.md",
  "extension/src/blankModel.js",
  "extension/src/extension.js",
  "extension/src/fingerprint.js",
  "extension/src/settings.js"
];

// Every text entry that must never carry a machine-local path or a credential.
const TEXT_ENTRIES = [
  "extension/package.json",
  "extension/readme.md",
  "extension/changelog.md",
  "extension/assets/manifest.json",
  "extension/assets/plugin/ahm-diagrammo.plugin.js",
  "extension/assets/library/ahm-diagrammo.xml",
  "extension/src/blankModel.js",
  "extension/src/extension.js",
  "extension/src/fingerprint.js",
  "extension/src/settings.js"
];

const SECRET_PATTERN = /(?:api[_-]?key|secret|password|BEGIN [A-Z ]*PRIVATE KEY|ghp_[A-Za-z0-9]{20,})/i;

function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

// Reading a zip entry must never be swallowed: a missing entry is a failure, not a skip.
function readEntry(vsix, entry) {
  const run = spawnSync("unzip", ["-p", vsix, entry], { maxBuffer: 32 * 1024 * 1024 });
  assert.equal(run.status, 0, "unzip -p failed for " + entry + ": " + String(run.stderr));
  assert.ok(run.stdout.length > 0, "entry " + entry + " is empty in the VSIX");
  return run.stdout;
}

describe("package-contents", function () {
  it("exactly one built VSIX is present", function () {
    assert.equal(vsixFiles.length, 1, "expected one .vsix, found: " + JSON.stringify(vsixFiles));
  });

  const vsix = path.join(extRoot, vsixFiles[0] || "missing.vsix");

  it("payload entry set equals the pinned allowlist", function () {
    const run = spawnSync("unzip", ["-Z1", vsix], { encoding: "utf8" });
    assert.equal(run.status, 0, "unzip -Z1 failed: " + run.stderr);
    const entries = run.stdout.split("\n").map(s => s.trim()).filter(Boolean).sort();
    assert.deepEqual(entries, EXPECTED_ENTRIES);
  });

  it("shipped assets match the source-of-truth digests", function () {
    const pluginAsset = readEntry(vsix, "extension/assets/plugin/ahm-diagrammo.plugin.js");
    const libraryAsset = readEntry(vsix, "extension/assets/library/ahm-diagrammo.xml");

    const health = fs.readFileSync(path.join(extRoot, "..", "plugin", "ahm-health.js"));
    const authoring = fs.readFileSync(path.join(extRoot, "plugin-src", "ahm-authoring.js"));
    const librarySource = fs.readFileSync(path.join(extRoot, "..", "library", "ahm-diagrammo.xml"));
    const expectedPlugin = sha256(Buffer.concat([health, Buffer.from("\n"), authoring]));

    assert.equal(sha256(pluginAsset), expectedPlugin,
      "packaged plugin digest does not match health + LF + authoring");
    assert.equal(sha256(libraryAsset), sha256(librarySource),
      "packaged library digest does not match the source library");

    const manifest = JSON.parse(readEntry(vsix, "extension/assets/manifest.json").toString("utf8"));
    assert.equal(manifest.pluginSha256, expectedPlugin,
      "packaged manifest was not regenerated by sync-assets before packaging");
    assert.equal(manifest.librarySha256, sha256(librarySource));
  });

  TEXT_ENTRIES.forEach(function (entry) {
    it("no absolute path or secret in " + entry, function () {
      const content = readEntry(vsix, entry).toString("utf8");
      assert.ok(!/\/Users\/|[A-Z]:\\/.test(content), "absolute path found in " + entry);
      assert.ok(!SECRET_PATTERN.test(content), "secret-like string found in " + entry);
    });
  });

  it("extensionDependencies and engines are correct", function () {
    const parsed = JSON.parse(readEntry(vsix, "extension/package.json").toString("utf8"));
    assert.deepEqual(parsed.extensionDependencies, ["hediet.vscode-drawio"]);
    assert.equal(parsed.engines.vscode, "^1.74.0");
  });
});
