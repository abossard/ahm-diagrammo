// gallery.mjs — renders docs/gallery/source.md into docs/gallery/README.md plus SVGs in docs/gallery/svg/.
// Health models render in both looks (swimlane and Pele); any other diagram renders once (Pele).
// A block preceded by `<!-- gallery: renderAhm {options} -->` (or a list of { label, options }) is
// rendered with the Pele library call instead, once per option set.
//
//   node scripts/gallery.mjs           write the gallery
//   node scripts/gallery.mjs --check   exit 1 when the committed gallery is out of date
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { prepareDocuments, renderDiagram, renderAhm, looksLikeHealthModel, slugify, Diagnostics } from "../src/index.mjs";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const GALLERY_DIR = join(ROOT, "docs", "gallery");
const GALLERY_COMMENT = /^<!--\s*gallery:\s*renderAhm\s+([\s\S]*?)\s*-->\s*$/;
const LOOK_LABEL = {
  swimlane: "Swimlane look (default)",
  pele: "Pele look (`-r pele`)",
  mermaid: "Pele, plain Mermaid shapes",
};

// source.md text → Map(relative path → file content) for README.md and every svg/*.svg
export function buildGallery(source) {
  const [doc] = prepareDocuments([{ name: "source.md", source }], { theme: "portal", renderer: "auto" });
  if (doc.diagnostics.length) throw new Error(doc.diagnostics.map((d) => d.message).join("; "));
  const lines = source.split("\n");
  const files = new Map();
  const readme = ["<!-- Generated by `npm run gallery` from source.md. Edit source.md, not this file. -->", ""];
  let cursor = 0;
  for (const block of doc.blocks) {
    const errors = block.issues.filter((i) => i.level === "error");
    if (errors.length) throw new Error(`source.md:${block.line} ${block.slug}: ${errors.map((e) => e.message).join("; ")}`);
    const fence = lines.slice(block.line - 1, block.closeLine);
    let above = block.line - 2;
    while (above >= cursor && !lines[above].trim()) above--;
    const comment = above >= cursor ? lines[above].match(GALLERY_COMMENT) : null;
    readme.push(...lines.slice(cursor, comment ? above : block.line - 1));

    // renders: [{ file, caption, svg }]
    const renders = [];
    if (comment) {
      const spec = JSON.parse(comment[1]);
      const views = Array.isArray(spec) ? spec : [{ label: "Pele library", options: spec }];
      for (const view of views) {
        const name = views.length > 1 ? `${block.slug}.${slugify(view.label)}.svg` : `${block.slug}.pele.svg`;
        renders.push({ file: name, caption: `${view.label} · \`renderAhm\``, svg: renderAhm(block.code, view.options).svg });
      }
    } else {
      const looks = block.options.renderer || !looksLikeHealthModel(block.code) ? [block.renderer] : ["swimlane", "pele"];
      for (const look of looks) {
        const diag = new Diagnostics({ file: "source.md" });
        const r = renderDiagram(block.code, { ...block.effectiveOptions, renderer: look, diag, baseLine: block.codeLine - 1 });
        for (const w of diag.warnings) console.warn(`warn  source.md:${w.line ?? block.line}  ${block.slug} [${look}]: ${w.message}`);
        const name = looks.length > 1 ? `${block.slug}.${look}.svg` : `${block.slug}.svg`;
        renders.push({ file: name, caption: LOOK_LABEL[r.renderer], svg: r.svg });
      }
    }

    for (const r of renders) {
      files.set(`svg/${r.file}`, r.svg);
      readme.push(`**${r.caption}**`, "", `![${block.heading}, ${r.caption.replace(/`/g, "")}](svg/${r.file})`, "");
    }
    readme.push("<details><summary>Source</summary>", "", "````markdown", ...(comment ? [lines[above]] : []), ...fence, "````", "", "</details>");
    cursor = block.closeLine;
  }
  readme.push(...lines.slice(cursor));
  files.set("README.md", readme.join("\n"));
  return files;
}

// files on disk that differ from the expected gallery: { stale: [paths], extra: [paths] }
export function compareGallery(files, dir = GALLERY_DIR) {
  const stale = [...files].filter(([path, content]) => !existsSync(join(dir, path)) || readFileSync(join(dir, path), "utf8") !== content).map(([path]) => path);
  const svgDir = join(dir, "svg");
  const extra = existsSync(svgDir) ? readdirSync(svgDir).map((name) => `svg/${name}`).filter((path) => !files.has(path)) : [];
  return { stale, extra };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = buildGallery(readFileSync(join(GALLERY_DIR, "source.md"), "utf8"));
  if (process.argv.includes("--check")) {
    const { stale, extra } = compareGallery(files);
    if (stale.length || extra.length) {
      for (const path of stale) console.error(`stale  docs/gallery/${path}`);
      for (const path of extra) console.error(`extra  docs/gallery/${path}`);
      console.error("\nThe gallery is out of date: run `npm run gallery` and commit the result.");
      process.exit(1);
    }
    console.log(`gallery is up to date (${files.size} files)`);
  } else {
    const { extra } = compareGallery(files);
    for (const path of extra) rmSync(join(GALLERY_DIR, path));
    mkdirSync(join(GALLERY_DIR, "svg"), { recursive: true });
    for (const [path, content] of files) writeFileSync(join(GALLERY_DIR, path), content, "utf8");
    console.log(`wrote docs/gallery/README.md and ${files.size - 1} SVGs${extra.length ? `, removed ${extra.length} stale` : ""}`);
  }
}
